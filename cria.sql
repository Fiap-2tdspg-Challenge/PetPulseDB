    WHEN VALUE_ERROR THEN

        INSERT INTO T_CLY_LOG_ERRO (
            nome_procedure,
            codigo_erro,
            mensagem_erro,
            usuario_banco
        )
        VALUES (
            'PRC_CARGA_PET',
            2,
            'Erro de valor informado',
            USER
        );

        DBMS_OUTPUT.PUT_LINE('Erro de valor');

    WHEN OTHERS THEN

        v_codigo := SQLCODE;
