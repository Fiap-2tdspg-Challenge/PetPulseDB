-- BLOCO ANTERIOR / ATUAL / PROXIMO
------------------------------------------------------------

DECLARE

    CURSOR c_pet IS
        SELECT id_pet, peso
        FROM T_CLY_PET
        ORDER BY id_pet;

    TYPE t_peso IS TABLE OF NUMBER INDEX BY PLS_INTEGER;

    v_pesos t_peso;

    v_index NUMBER := 0;

BEGIN

    FOR r IN c_pet LOOP

        v_index := v_index + 1;

        v_pesos(v_index) := r.peso;

    END LOOP;

    FOR i IN 1 .. v_pesos.COUNT LOOP

        DBMS_OUTPUT.PUT_LINE(

            'Anterior: ' ||

            CASE
                WHEN i = 1 THEN 'Vazio'
                ELSE TO_CHAR(v_pesos(i - 1))
            END ||

            ' | Atual: ' ||

            TO_CHAR(v_pesos(i)) ||

            ' | Próximo: ' ||

            CASE
                WHEN i = v_pesos.COUNT THEN 'Vazio'
                ELSE TO_CHAR(v_pesos(i + 1))
            END

        );

    END LOOP;

END;
