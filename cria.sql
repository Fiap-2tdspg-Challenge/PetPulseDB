-- Relatório JOIN + GROUP BY

DECLARE

    CURSOR c_relatorio IS
        SELECT
            p.especie,
            COUNT(h.id_historico)
        FROM T_CLY_PET p
        INNER JOIN T_CLY_HISTORICO_CLINICO h
            ON p.id_pet = h.id_pet
        GROUP BY p.especie
        ORDER BY p.especie;

    v_especie   VARCHAR2(50);
    v_total     NUMBER;

BEGIN

    OPEN c_relatorio;

    LOOP

        FETCH c_relatorio INTO v_especie, v_total;

        EXIT WHEN c_relatorio%NOTFOUND;

        DBMS_OUTPUT.PUT_LINE(
            'Espécie: ' || v_especie ||
            ' | Total registros: ' || v_total
        );

    END LOOP;

    CLOSE c_relatorio;

END;
