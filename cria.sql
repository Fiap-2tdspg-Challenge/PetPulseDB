-- Relatório JOIN + GROUP BY + ORDER BY:

DECLARE

    CURSOR c_relatorio IS
        SELECT
            u.nome AS tutor,
            COUNT(p.id_pet) AS total_pets
        FROM T_CLY_USUARIO u
        INNER JOIN T_CLY_PET p
            ON u.id_usuario = p.id_usuario
        GROUP BY u.nome
        ORDER BY total_pets DESC;

    v_tutor       VARCHAR2(150);
    v_total_pets  NUMBER;

BEGIN

    OPEN c_relatorio;

    LOOP

        FETCH c_relatorio INTO v_tutor, v_total_pets;

        EXIT WHEN c_relatorio%NOTFOUND;

        DBMS_OUTPUT.PUT_LINE(
            'Tutor: ' || v_tutor ||
            ' | Total Pets: ' || v_total_pets
        );

    END LOOP;

    CLOSE c_relatorio;

END;
/

-- Relatório JOIN:

DECLARE

    CURSOR c_relatorio IS
