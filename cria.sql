------------------------------------------------------------
-- BLOCO ANTERIOR / ATUAL / PROXIMO
------------------------------------------------------------

DECLARE

    CURSOR c_pet IS
        SELECT id_pet, nome
        FROM T_CLY_PET
        ORDER BY id_pet;

    v_anterior VARCHAR2(100);
    v_atual    VARCHAR2(100);
    v_proximo  VARCHAR2(100);

BEGIN

    OPEN c_pet;

    FETCH c_pet INTO v_anterior, v_atual;

    LOOP

        FETCH c_pet INTO v_proximo, v_atual;

        EXIT WHEN c_pet%NOTFOUND;

        DBMS_OUTPUT.PUT_LINE(
            'Anterior: ' || v_anterior ||
            ' | Atual: ' || v_atual ||
            ' | Próximo: ' || v_proximo
        );

        v_anterior := v_proximo;

    END LOOP;

    CLOSE c_pet;

END;
