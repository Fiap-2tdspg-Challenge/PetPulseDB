        DBMS_OUTPUT.PUT_LINE(
            'Pet: ' || v_pet ||
            ' | Alerta: ' || v_alerta ||
            ' | Risco: ' || v_risco
        );

    END LOOP;

    CLOSE c_relatorio;

END;
