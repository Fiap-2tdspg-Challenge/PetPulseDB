        p_raca,
        p_dt_nascimento,
        p_peso,
        p_sexo,
        p_castrado,
        p_porte
    );

    DBMS_OUTPUT.PUT_LINE('Pet cadastrado com sucesso');

EXCEPTION

    WHEN VALUE_ERROR THEN

        INSERT INTO T_CLY_LOG_ERRO (
            nome_procedure,
            mensagem_erro,
            usuario_banco
        )
        VALUES (
            'PRC_CARGA_PET',
            'Erro de valor informado',
            USER
        );

        DBMS_OUTPUT.PUT_LINE('Erro de valor');

    WHEN OTHERS THEN

        v_erro := SQLERRM;

        INSERT INTO T_CLY_LOG_ERRO (
            nome_procedure,
            mensagem_erro,
            usuario_banco
        )
        VALUES (
            'PRC_CARGA_PET',
            v_erro,
            USER
