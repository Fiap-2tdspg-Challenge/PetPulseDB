-- USUARIO CADASTRADO:

DECLARE

    CURSOR c_usuarios IS
        SELECT nome, email
        FROM T_CLY_USUARIO;

    v_nome  VARCHAR2(150);
    v_email VARCHAR2(150);

BEGIN

    OPEN c_usuarios;

    LOOP

        FETCH c_usuarios INTO v_nome, v_email;

