-- PROCEDURE: T_CLY_USUARIO

CREATE OR REPLACE PROCEDURE PRC_CARGA_USUARIO (
    p_nome        IN VARCHAR2,
    p_cpf         IN VARCHAR2,
    p_email       IN VARCHAR2,
    p_senha       IN VARCHAR2,
    p_telefone    IN VARCHAR2,
    p_endereco    IN VARCHAR2
)
IS

    v_erro VARCHAR2(4000);

BEGIN

    IF LENGTH(p_cpf) < 11 THEN
        RAISE_APPLICATION_ERROR(-20001, 'CPF inválido');
    END IF;

    INSERT INTO T_CLY_USUARIO (
        nome,
        cpf,
        email,
        senha,
        telefone,
        endereco
    )
    VALUES (
        p_nome,
        p_cpf,
        p_email,
        p_senha,
        p_telefone,
        p_endereco
    );

    DBMS_OUTPUT.PUT_LINE('Usuário cadastrado com sucesso');

EXCEPTION

    WHEN DUP_VAL_ON_INDEX THEN

        INSERT INTO T_CLY_LOG_ERRO (
            nome_procedure,
            mensagem_erro,
            usuario_banco
        )
        VALUES (
            'PRC_CARGA_USUARIO',
            'CPF ou EMAIL já cadastrado',
            USER
        );

        DBMS_OUTPUT.PUT_LINE('Erro: CPF ou EMAIL já existente');

    WHEN VALUE_ERROR THEN

        INSERT INTO T_CLY_LOG_ERRO (
            nome_procedure,
            mensagem_erro,
            usuario_banco
        )
        VALUES (
            'PRC_CARGA_USUARIO',
            'Erro de valor informado',
            USER
        );

        DBMS_OUTPUT.PUT_LINE('Erro de valor');

    WHEN OTHERS THEN

        v_erro := SQLERRM;

        INSERT INTO T_CLY_LOG_ERRO (
            nome_procedure,
            mensagem_erro,
            usuario_banco
        )
        VALUES (
            'PRC_CARGA_USUARIO',
            v_erro,
            USER
        );

        DBMS_OUTPUT.PUT_LINE('Erro geral: ' || v_erro);

END;
