    ID_HISTORICO        NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ID_PET              NUMBER          NOT NULL,
    ID_PROFISSIONAL     NUMBER,
    TIPO_REGISTRO       VARCHAR2(50),
    DESCRICAO           VARCHAR2(500),
    DT_REGISTRO         DATE DEFAULT SYSDATE NOT NULL,
    DT_RETORNO          DATE,
    OBSERVACOES         VARCHAR2(1000),

    CONSTRAINT PK_CLY_HISTORICO
        PRIMARY KEY (ID_HISTORICO),

    CONSTRAINT FK_CLY_HIST_PET
