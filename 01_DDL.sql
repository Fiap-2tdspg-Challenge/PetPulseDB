    CONSTRAINT CK_CLY_ALERTA_ORIGEM
        CHECK (ORIGEM_ALERTA IN ('HISTORICO_CLINICO', 'DISPOSITIVO_IOT', 'SISTEMA', 'USUARIO')),

    CONSTRAINT CK_CLY_ALERTA_STATUS
        CHECK (STATUS IN ('ABERTO', 'VISUALIZADO', 'RESOLVIDO'))
