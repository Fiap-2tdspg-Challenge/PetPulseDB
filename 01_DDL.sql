------------------------------------------------------------
-- TABELA: PET
------------------------------------------------------------
CREATE TABLE T_CLY_PET (
    ID_PET            NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ID_USUARIO        NUMBER          NOT NULL,
    ID_ESPECIE        NUMBER          NOT NULL,
    ID_RACA           NUMBER          NOT NULL,
    ID_PORTE          NUMBER          NOT NULL,
    NOME              VARCHAR2(100)   NOT NULL,
    DT_NASCIMENTO     DATE,
    PESO              NUMBER(6,2),
    SEXO              CHAR(1)         NOT NULL,
    CASTRADO          CHAR(1)         DEFAULT 'N' NOT NULL,
    DT_CADASTRO       DATE DEFAULT SYSDATE NOT NULL,

    CONSTRAINT PK_CLY_PET
        PRIMARY KEY (ID_PET),

    CONSTRAINT FK_CLY_PET_USUARIO
        FOREIGN KEY (ID_USUARIO)
        REFERENCES T_CLY_USUARIO(ID_USUARIO),

    CONSTRAINT FK_CLY_PET_ESPECIE
        FOREIGN KEY (ID_ESPECIE)
        REFERENCES T_CLY_ESPECIE(ID_ESPECIE),

    CONSTRAINT FK_CLY_PET_RACA
        FOREIGN KEY (ID_RACA)
        REFERENCES T_CLY_RACA(ID_RACA),

    CONSTRAINT FK_CLY_PET_PORTE
        FOREIGN KEY (ID_PORTE)
        REFERENCES T_CLY_PORTE(ID_PORTE),

    CONSTRAINT CK_CLY_PET_SEXO
        CHECK (UPPER(SEXO) IN ('M', 'F')),

    CONSTRAINT CK_CLY_PET_CASTRADO
        CHECK (UPPER(CASTRADO) IN ('S', 'N')),

    CONSTRAINT CK_CLY_PET_PESO
        CHECK (PESO IS NULL OR PESO > 0)
);

------------------------------------------------------------
-- TABELA: DISPOSITIVO IOT
------------------------------------------------------------
CREATE TABLE T_CLY_DISPOSITIVO_IOT (
    ID_DISPOSITIVO            NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ID_PET                    NUMBER        NOT NULL,
    DT_ATIVACAO               DATE DEFAULT SYSDATE NOT NULL,
    INTERVALO_COLETA_MIN      NUMBER(5),
    FREQUENCIA_CARDIACA       NUMBER(5),
    NIVEL_ATIVIDADE           NUMBER(5,2),
    PRESSAO                   NUMBER(6,2),
    DT_ULTIMA_LEITURA         DATE,
    STATUS                    VARCHAR2(20)  DEFAULT 'ATIVO' NOT NULL,

    CONSTRAINT PK_CLY_DISPOSITIVO_IOT
        PRIMARY KEY (ID_DISPOSITIVO),

    CONSTRAINT FK_CLY_DISP_PET
        FOREIGN KEY (ID_PET)
        REFERENCES T_CLY_PET(ID_PET),

    CONSTRAINT UK_CLY_DISPOSITIVO_PET
        UNIQUE (ID_PET),

    CONSTRAINT CK_CLY_DISP_STATUS
        CHECK (STATUS IN ('ATIVO', 'INATIVO', 'MANUTENCAO')),

    CONSTRAINT CK_CLY_DISP_INTERVALO
        CHECK (INTERVALO_COLETA_MIN IS NULL OR INTERVALO_COLETA_MIN > 0),

    CONSTRAINT CK_CLY_DISP_FC
        CHECK (FREQUENCIA_CARDIACA IS NULL OR FREQUENCIA_CARDIACA > 0),

    CONSTRAINT CK_CLY_DISP_ATIVIDADE
        CHECK (NIVEL_ATIVIDADE IS NULL OR NIVEL_ATIVIDADE >= 0),

    CONSTRAINT CK_CLY_DISP_PRESSAO
        CHECK (PRESSAO IS NULL OR PRESSAO > 0)
);

