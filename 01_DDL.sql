------------------------------------------------------------
-- TABELA: USUARIO
------------------------------------------------------------
CREATE TABLE T_CLY_USUARIO (
    ID_USUARIO        NUMBER GENERATED BY DEFAULT AS IDENTITY,
    NOME              VARCHAR2(150)    NOT NULL,
    CPF               VARCHAR2(14)     NOT NULL,
    EMAIL             VARCHAR2(150)    NOT NULL,
    SENHA             VARCHAR2(255)    NOT NULL,
    DT_CADASTRO       DATE DEFAULT SYSDATE NOT NULL,

    CONSTRAINT PK_CLY_USUARIO
        PRIMARY KEY (ID_USUARIO),

    CONSTRAINT UK_CLY_USUARIO_CPF
        UNIQUE (CPF),

    CONSTRAINT UK_CLY_USUARIO_EMAIL
        UNIQUE (EMAIL)
);

------------------------------------------------------------
-- TABELA: ENDERECO_USUARIO
------------------------------------------------------------
CREATE TABLE T_CLY_ENDERECO_USUARIO (
    SEQ_ENDERECO_USUARIO    NUMBER(10)      NOT NULL,
    ID_USUARIO              NUMBER          NOT NULL,
    COD_TIPO_ENDERECO       NUMBER(2)       NOT NULL,
    COD_CIDADE              NUMBER(10)      NOT NULL,
    DES_ENDERECO            VARCHAR2(150)   NOT NULL,
    NUM_ENDERECO            VARCHAR2(20),
    DES_COMPLEMENTO         VARCHAR2(100),
    NUM_CEP                 VARCHAR2(9),
    DES_BAIRRO              VARCHAR2(100),
    STA_ATIVO               CHAR(1) DEFAULT 'S',
    DAT_CADASTRO            DATE DEFAULT SYSDATE,

    CONSTRAINT PK_CLY_END_USUARIO
        PRIMARY KEY (SEQ_ENDERECO_USUARIO),

    CONSTRAINT FK_CLY_END_USUARIO_USUARIO
        FOREIGN KEY (ID_USUARIO)
        REFERENCES T_CLY_USUARIO(ID_USUARIO),

    CONSTRAINT FK_CLY_END_USUARIO_TIPO
        FOREIGN KEY (COD_TIPO_ENDERECO)
        REFERENCES T_CLY_TIPO_ENDERECO(COD_TIPO_ENDERECO),

    CONSTRAINT FK_CLY_END_USUARIO_CIDADE
        FOREIGN KEY (COD_CIDADE)
        REFERENCES T_CLY_CIDADE(COD_CIDADE),

    CONSTRAINT CK_CLY_END_STA_ATIVO
        CHECK (UPPER(STA_ATIVO) IN ('S', 'N'))
);

