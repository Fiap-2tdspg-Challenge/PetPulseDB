-- TABELA: ALERTA INTELIGENTE
------------------------------------------------------------
CREATE TABLE T_CLY_ALERTA_INTELIGENTE (
    ID_ALERTA           NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ID_PET              NUMBER          NOT NULL,
    ID_TIPO_ALERTA      NUMBER          NOT NULL,
    NIVEL_RISCO         VARCHAR2(20),
    ORIGEM_ALERTA       VARCHAR2(50),
    MENSAGEM            VARCHAR2(500),
    RECOMENDACAO        VARCHAR2(1000),
    DT_GERACAO          DATE DEFAULT SYSDATE NOT NULL,
    STATUS              VARCHAR2(20)    DEFAULT 'ABERTO' NOT NULL,

    CONSTRAINT PK_CLY_ALERTA
        PRIMARY KEY (ID_ALERTA),

    CONSTRAINT FK_CLY_ALERTA_PET
        FOREIGN KEY (ID_PET)
